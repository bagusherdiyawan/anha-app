<p>Selamat datang di ANHA Electric. Kami menghargai privasi Anda dan berkomitmen untuk melindungi data pribadi Anda. Kebijakan Privasi ini menjelaskan bagaimana kami mengumpulkan, menggunakan, mengungkapkan, dan menjaga informasi Anda ketika Anda mengunjungi situs web atau menggunakan aplikasi kami.</p>
<h2>1. Informasi yang Kami Kumpulkan</h2>
<p>Kami dapat mengumpulkan berbagai jenis informasi sehubungan dengan layanan yang kami sediakan, termasuk:</p>
<ul>
<li><strong>Informasi Pribadi:</strong> Nama lengkap, alamat email, nomor telepon, alamat pengiriman, dan alamat penagihan yang Anda berikan saat mendaftar atau melakukan pembelian.</li>
<li><strong>Data Transaksi:</strong> Rincian tentang pembayaran dan produk yang Anda beli dari kami.</li>
<li><strong>Data Penggunaan:</strong> Informasi tentang bagaimana Anda berinteraksi dengan situs web dan aplikasi kami, seperti alamat IP, jenis browser, halaman yang dikunjungi, dan waktu akses.</li>
</ul>
<h2>2. Bagaimana Kami Menggunakan Informasi Anda</h2>
<p>Informasi yang kami kumpulkan digunakan untuk berbagai tujuan operasional dan peningkatan layanan, antara lain:</p>
<ul>
<li>Memproses dan mengelola pesanan, pembayaran, dan pengiriman produk.</li>
<li>Menyediakan dukungan pelanggan dan menanggapi pertanyaan atau permintaan Anda.</li>
<li>Meningkatkan pengalaman pengguna di platform kami.</li>
<li>Mengirimkan pemberitahuan penting terkait layanan, perubahan kebijakan, atau masalah teknis.</li>
<li>Dengan persetujuan Anda, mengirimkan materi promosi atau penawaran khusus.</li>
</ul>
<h2>3. Perlindungan dan Keamanan Data</h2>
<p>Kami menerapkan langkah-langkah keamanan teknis dan organisasi yang sesuai untuk melindungi data pribadi Anda dari akses yang tidak sah, kehilangan, atau pengungkapan. Transaksi pembayaran dienkripsi dan kami secara teratur memantau sistem kami untuk celah keamanan.</p>
<p>Meskipun kami berusaha keras untuk melindungi informasi Anda, tidak ada metode transmisi di internet atau metode penyimpanan elektronik yang 100% aman. Oleh karena itu, kami tidak dapat menjamin keamanan mutlak.</p>
<h2>4. Berbagi Informasi dengan Pihak Ketiga</h2>
<p>Kami tidak menjual, memperdagangkan, atau menyewakan informasi identifikasi pribadi Anda kepada orang lain. Kami mungkin membagikan informasi agregat demografis generik yang tidak terkait dengan informasi identifikasi pribadi apapun mengenai pengunjung dan pengguna dengan mitra bisnis, afiliasi terpercaya, dan pengiklan kami untuk tujuan yang disebutkan di atas.</p>
<p>Kami juga mungkin mempekerjakan penyedia layanan pihak ketiga (seperti layanan kurir pengiriman atau gateway pembayaran) untuk membantu kami mengoperasikan bisnis atau mengelola aktivitas atas nama kami. Pihak ketiga ini memiliki akses ke data pribadi Anda hanya untuk melakukan tugas tersebut atas nama kami dan berkewajiban untuk tidak mengungkapkan atau menggunakannya untuk tujuan lain.</p>
<h2>5. Hak Anda</h2>
<p>Anda memiliki hak untuk mengakses, memperbarui, atau menghapus informasi pribadi yang kami miliki tentang Anda. Jika Anda ingin melaksanakan hak-hak ini atau memiliki pertanyaan tentang praktik privasi kami, silakan hubungi kami melalui informasi kontak yang disediakan di bawah ini.</p>
<h2>6. Perubahan Kebijakan Privasi</h2>
<p>Kami dapat memperbarui Kebijakan Privasi ini dari waktu ke waktu untuk mencerminkan, misalnya, perubahan pada praktik kami atau untuk alasan operasional, hukum, atau peraturan lainnya. Perubahan akan berlaku segera setelah diposting di halaman ini. Kami menyarankan Anda untuk meninjau halaman ini secara berkala untuk mengetahui informasi terbaru tentang praktik privasi kami.</p>
